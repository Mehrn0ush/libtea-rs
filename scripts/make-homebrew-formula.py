#!/usr/bin/env python3
"""Write the Homebrew formula for a libtea release.

    make-homebrew-formula.py --version V --sums PATH

Reads the release's SHA256SUMS (verify it first: `gh attestation verify
SHA256SUMS ... --source-ref refs/tags/vV`, docs/installing.md) and prints
Formula/libtea.rb for the Mehrn0ush/homebrew-tap repository on stdout. macOS
gets the darwin archives; Linux gets the statically linked musl archives, so
the formula does not depend on the host's glibc. Homebrew checks the SHA-256
in the formula; it does not check the attestation.

Fails if SHA256SUMS lacks one of the four archives or a line is malformed.
"""
import argparse
import re
import sys

VERSION_RE = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+$")
LINE_RE = re.compile(r"^([0-9a-f]{64})  (\S+)$")
REPO = "https://github.com/Mehrn0ush/libtea-rs"

# (Homebrew block, CPU block, release target)
TARGETS = [
    ("on_macos", "on_arm", "aarch64-apple-darwin"),
    ("on_macos", "on_intel", "x86_64-apple-darwin"),
    ("on_linux", "on_arm", "aarch64-unknown-linux-musl"),
    ("on_linux", "on_intel", "x86_64-unknown-linux-musl"),
]


def read_sums(path):
    sums = {}
    with open(path, encoding="utf-8") as handle:
        for number, line in enumerate(handle, 1):
            match = LINE_RE.match(line.rstrip("\n"))
            if not match:
                sys.exit(f"{path}:{number}: not a SHA256SUMS line")
            sums[match.group(2)] = match.group(1)
    return sums


def formula(version, sums):
    lines = [
        "# Generated by scripts/make-homebrew-formula.py in Mehrn0ush/libtea-rs.",
        "# Do not edit by hand; regenerate from the release's SHA256SUMS.",
        "class Libtea < Formula",
        '  desc "CLI for the CycloneDX Transparency Exchange API (TEA)"',
        f'  homepage "{REPO}"',
        f'  version "{version}"',
        '  license "Apache-2.0"',
    ]
    for os_block in ("on_macos", "on_linux"):
        lines.append("")
        lines.append(f"  {os_block} do")
        for block, cpu, target in TARGETS:
            if block != os_block:
                continue
            name = f"libtea-{version}-{target}.tar.gz"
            if name not in sums:
                sys.exit(f"SHA256SUMS has no {name}")
            lines += [
                f"    {cpu} do",
                f'      url "{REPO}/releases/download/v{version}/{name}"',
                f'      sha256 "{sums[name]}"',
                "    end",
            ]
        lines.append("  end")
    lines += [
        "",
        "  def install",
        '    bin.install "libtea"',
        "  end",
        "",
        "  test do",
        '    assert_match "libtea #{version}", shell_output("#{bin}/libtea --version")',
        "  end",
        "end",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--version", required=True)
    parser.add_argument("--sums", required=True)
    args = parser.parse_args()
    if not VERSION_RE.match(args.version):
        sys.exit(f"bad version: {args.version!r}")
    sys.stdout.write(formula(args.version, read_sums(args.sums)))


if __name__ == "__main__":
    main()
